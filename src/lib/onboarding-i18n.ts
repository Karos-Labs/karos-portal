export type MsgKey = keyof typeof STRINGS;

/** A message in `lang`, with `{placeholders}` filled. English when a language is missing (it never is: the table is typed). */
export function tr(lang: ChatLang, key: MsgKey, vars: Record<string, string | number> = {}): string {
  const text: string = (STRINGS[key] as Dict)[lang] ?? (STRINGS[key] as Dict).en;
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

