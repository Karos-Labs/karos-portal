/**
 * Every word the onboarding chat and its wizard show, in every language the
 * client can pick from the dropdown (owner ruling 2026-09-26: "not just
 * English and Hebrew - Portuguese, Arabic, French, Spanish and the rest, as a
 * select list at the top; the first message in English only").
 *
 * One table, keyed by message, so a missing translation is a type error
 * rather than a blank bubble. Pure and client-safe.
 */

export const CHAT_LANGUAGES = [
  { code: "en", label: "English", english: "English", rtl: false },
  { code: "he", label: "עברית", english: "Hebrew", rtl: true },
  { code: "ar", label: "العربية", english: "Arabic", rtl: true },
  { code: "es", label: "Español", english: "Spanish", rtl: false },
  { code: "fr", label: "Français", english: "French", rtl: false },
  { code: "pt", label: "Português", english: "Portuguese", rtl: false },
  { code: "de", label: "Deutsch", english: "German", rtl: false },
  { code: "it", label: "Italiano", english: "Italian", rtl: false },
  { code: "ru", label: "Русский", english: "Russian", rtl: false },
] as const;

export type ChatLang = (typeof CHAT_LANGUAGES)[number]["code"];

const CODES = new Set<string>(CHAT_LANGUAGES.map((l) => l.code));

export function isChatLang(v: unknown): v is ChatLang {
  return typeof v === "string" && CODES.has(v);
}

export function isRtl(lang: ChatLang): boolean {
  return CHAT_LANGUAGES.find((l) => l.code === lang)?.rtl ?? false;
}

/** The language's English name ("Portuguese"), for prompts and stored briefs. */
export function languageName(lang: ChatLang): string {
  return CHAT_LANGUAGES.find((l) => l.code === lang)?.english ?? "English";
}

/** The language's own name ("Português"), for the dropdown and chips. */
export function languageLabel(lang: ChatLang): string {
  return CHAT_LANGUAGES.find((l) => l.code === lang)?.label ?? lang;
}

